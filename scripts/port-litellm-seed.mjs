// Regenerate src/core/litellm-seed.ts from TokenTracker's bundled LiteLLM
// snapshot (TokenTracker src/lib/pricing/seed-snapshot.json, MIT; the data
// itself is BerriAI/litellm model_prices_and_context_window.json, MIT).
//
//   node scripts/port-litellm-seed.mjs ~/projects/reference/TokenTracker/src/lib/pricing/seed-snapshot.json
//
// Converts per-token USD to per-million USD exactly like TokenTracker's
// convertLitellmEntry (rounded to 10 decimals) so lookups need no runtime math.
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const src = process.argv[2]
if (!src) {
  console.error("usage: node scripts/port-litellm-seed.mjs <seed-snapshot.json>")
  process.exit(2)
}
const raw = JSON.parse(fs.readFileSync(src, "utf8"))
const round = (n) => Math.round(n * 1e10) / 1e10
const out = {}
for (const [name, e] of Object.entries(raw)) {
  if (name.startsWith("_") || name === "sample_spec" || !e || typeof e !== "object") continue
  const p = {}
  if (typeof e.input_cost_per_token === "number") p.input = round(e.input_cost_per_token * 1e6)
  if (typeof e.output_cost_per_token === "number") p.output = round(e.output_cost_per_token * 1e6)
  if (typeof e.cache_read_input_token_cost === "number") p.cache_read = round(e.cache_read_input_token_cost * 1e6)
  if (typeof e.cache_creation_input_token_cost === "number") p.cache_write = round(e.cache_creation_input_token_cost * 1e6)
  if (Object.keys(p).length) out[name] = p
}
const meta = raw._meta ?? {}
const here = path.dirname(fileURLToPath(import.meta.url))
const dest = path.join(here, "..", "src", "core", "litellm-seed.ts")
const body =
  `// GENERATED by scripts/port-litellm-seed.mjs — do not edit by hand.\n` +
  `// Source: TokenTracker src/lib/pricing/seed-snapshot.json (MIT), itself a\n` +
  `// snapshot of ${meta.source ?? "BerriAI/litellm model_prices_and_context_window.json"} (MIT)\n` +
  `// generated_at ${meta.generated_at ?? "unknown"}. Units: USD per million tokens.\n` +
  `// eslint-disable-next-line\n` +
  `export const LITELLM_SEED: Record<string, { input?: number; output?: number; cache_read?: number; cache_write?: number }> = ${JSON.stringify(out)}\n`
fs.writeFileSync(dest, body)
console.log(`wrote ${Object.keys(out).length} models -> ${dest}`)
